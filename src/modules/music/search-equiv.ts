/**
 * 把繁体 / 异体字折到组内首字（简体规范字），用于**元数据匹配**时的归一：
 * 库里是「鮮花」、在线源回「鲜花」，不折一下就永远对不上。
 * 与搜索用的字符类是同一张表，只是这里取「多对一」而不是「一对多」。
 */
const FOLD: Map<string, string> = (() => {
  const m = new Map<string, string>();
  for (const group of EQUIV_RAW.split(/\s+/)) {
    if (!group) continue;
    // 组首字可能是非 BMP（表里收了扩展区），用展开取码点，别用 group[0]
    const head = [...group][0];
    for (const ch of group) if (!m.has(ch)) m.set(ch, head);
  }
  return m;
})();

export function foldHan(s: string): string {
  let out = '';
  for (const ch of String(s ?? '')) out += FOLD.get(ch) ?? ch;
  return out;
}
