#!/usr/bin/env node
/**
 * 从 `contracts/openapi.json` 生成最小可用 SDK（TypeScript / Python）。
 *
 * 只做**薄封装**：每个 operationId 一个方法，参数统一收 `params` 对象，
 * 路径参数自动替换、其余按方法分给 query 或 body。不引第三方 HTTP 库
 * （TS 用 `fetch`，Python 用 `urllib`），也不生成"框架"。
 *
 * 用法：
 *   node tool/gen-sdk.js            生成 sdk/typescript 与 sdk/python
 *   node tool/gen-sdk.js --check    只校验生成物是否过期（已进 verify）
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const specPath = path.join(root, 'contracts', 'openapi.json');
const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));
const schemas = spec.components.schemas || {};
const checkOnly = process.argv.includes('--check');

// ---------------------------------------------------------------- TypeScript 类型

function tsType(s, indent = 0) {
  if (!s) return 'unknown';
  if (s.$ref) return s.$ref.split('/').pop();
  if (s.anyOf || s.oneOf) {
    const parts = (s.anyOf || s.oneOf).map((x) => tsType(x, indent));
    return [...new Set(parts)].join(' | ');
  }
  if (s.allOf) return s.allOf.map((x) => tsType(x, indent)).join(' & ');
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (s.type === 'array') return `${tsType(s.items, indent)}[]`;
  if (s.type === 'object' || s.properties) {
    const props = s.properties || {};
    const required = new Set(s.required || []);
    const pad = ' '.repeat(indent + 2);
    const lines = Object.entries(props).map(
      ([k, v]) =>
        `${pad}${JSON.stringify(k)}${required.has(k) ? '' : '?'}: ${tsType(v, indent + 2)};`,
    );
    if (lines.length === 0) return 'Record<string, unknown>';
    return `{\n${lines.join('\n')}\n${' '.repeat(indent)}}`;
  }
  if (s.type === 'integer' || s.type === 'number') return 'number';
  if (s.type === 'boolean') return 'boolean';
  if (s.type === 'string') return 'string';
  if (s.type === 'null') return 'null';
  return 'unknown';
}

function buildTypesTs() {
  const out = [
    '// AUTO-GENERATED by tool/gen-sdk.js from contracts/openapi.json — DO NOT EDIT.',
    '// 重新生成：npm run sdk',
    '',
  ];
  for (const [name, schema] of Object.entries(schemas)) {
    out.push(`export type ${name} = ${tsType(schema)};`, '');
  }
  return out.join('\n');
}

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

function collectOps() {
  const ops = [];
  for (const [p, item] of Object.entries(spec.paths || {})) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op || !op.operationId) continue;
      ops.push({
        path: p,
        method: method.toUpperCase(),
        id: op.operationId,
        summary: op.summary || '',
      });
    }
  }
  return ops.sort((a, b) => a.id.localeCompare(b.id));
}

function buildClientTs(ops) {
  const methods = ops
    .map(
      (o) => `  /** ${o.summary.replace(/\*\//g, '*\\/')} */
  async ${o.id}(params: Record<string, any> = {}): Promise<any> {
    return this.request('${o.method}', '${o.path}', params, '${o.method === 'GET' || o.method === 'DELETE' ? 'query' : 'body'}');
  }`,
    )
    .join('\n\n');

  return `// AUTO-GENERATED by tool/gen-sdk.js from contracts/openapi.json — DO NOT EDIT.
// 重新生成：npm run sdk

export interface ClientOptions {
  /** 内核地址，如 http://127.0.0.1:7788 */
  baseUrl: string;
  /** Bearer token（登录接口或 /auth/dev-token 获取） */
  token?: string;
  /** 额外请求头 */
  headers?: Record<string, string>;
}

export class ColanasClient {
  private token?: string;

  constructor(private readonly opts: ClientOptions) {
    this.token = opts.token;
  }

  setToken(token: string): void {
    this.token = token;
  }

  private async request(
    method: string,
    path: string,
    params: Record<string, any>,
    location: 'query' | 'body',
  ): Promise<any> {
    const used = new Set([...path.matchAll(/{([^}]+)}/g)].map((m) => m[1]));
    const rest = Object.fromEntries(Object.entries(params).filter(([k]) => !used.has(k)));
    const url = new URL(this.opts.baseUrl.replace(/\\/+$/, '') + path.replace(/{([^}]+)}/g, (_, k) => encodeURIComponent(String(params[k] ?? ''))));
    if (location === 'query') {
      for (const [k, v] of Object.entries(rest)) if (v !== undefined && v !== null) url.searchParams.set(k, String(v));
    }

    const headers: Record<string, string> = { ...(this.opts.headers || {}) };
    if (this.token) headers.authorization = 'Bearer ' + this.token;
    let body: string | undefined;
    if (location === 'body' && Object.keys(rest).length > 0) {
      headers['content-type'] = 'application/json';
      body = JSON.stringify(rest);
    }

    const res = await fetch(url, { method, headers, body });
    const text = await res.text();
    const data = text ? JSON.parse(text) : null;
    if (!res.ok) {
      const message = (data && (data.message || data.error)) || res.statusText;
      throw new Error(\`HTTP \${res.status} \${method} \${path}: \${message}\`);
    }
    return data;
  }

${methods}
}
`;
}

function snake(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .toLowerCase();
}

function buildClientPy(ops) {
  const methods = ops
    .map(
      (o) => `    def ${snake(o.id)}(self, **params):
        """${o.summary.replace(/"/g, "'")}"""
        return self._request(${JSON.stringify(o.method)}, ${JSON.stringify(o.path)}, params, ${JSON.stringify(o.method === 'GET' || o.method === 'DELETE' ? 'query' : 'body')})`,
    )
    .join('\n\n');

  return `"""AUTO-GENERATED by tool/gen-sdk.js from contracts/openapi.json — DO NOT EDIT.

用法：
    from colanas.client import ColanasClient
    c = ColanasClient("http://127.0.0.1:7788", token)
    print(c.files_list(path="/"))
"""

import json
import urllib.parse
import urllib.request


class ColanasClient:
    def __init__(self, base_url, token=None, headers=None):
        self.base_url = base_url.rstrip("/")
        self.token = token
        self.headers = dict(headers or {})

    def set_token(self, token):
        self.token = token

    def _request(self, method, path, params, location):
        import re

        used = set(re.findall(r"{([^}]+)}", path))
        for key in used:
            path = path.replace("{" + key + "}", urllib.parse.quote(str(params.get(key, ""))))
        rest = {k: v for k, v in params.items() if k not in used}

        url = self.base_url + path
        headers = dict(self.headers)
        if self.token:
            headers["authorization"] = "Bearer " + self.token

        body = None
        if location == "query":
            query = {k: v for k, v in rest.items() if v is not None}
            if query:
                url += "?" + urllib.parse.urlencode(query)
        elif rest:
            body = json.dumps(rest).encode("utf-8")
            headers["content-type"] = "application/json"

        req = urllib.request.Request(url, data=body, headers=headers, method=method)
        try:
            with urllib.request.urlopen(req, timeout=30) as res:
                raw = res.read().decode("utf-8")
                return json.loads(raw) if raw else None
        except urllib.error.HTTPError as err:
            raw = err.read().decode("utf-8")
            raise RuntimeError("HTTP %d %s %s: %s" % (err.code, method, path, raw)) from err

${methods}
`;
}

function buildReadme() {
  return `# ColaNasOs SDK

> 由 \`npm run sdk\` 从 \`contracts/openapi.json\` 生成，**不要手改**；\`npm run sdk.check\`（已进 \`verify\`）会拦截过期文件。

## TypeScript

\`\`\`ts
import { ColanasClient } from './client';

const client = new ColanasClient({ baseUrl: 'http://127.0.0.1:7788', token });
const books = await client.bookList({ limit: 20 });
\`\`\`

- 依赖 \`fetch\`（Node 18+ / 浏览器 / Deno / Bun 均可用），不引第三方 HTTP 库；
- 每个 \`operationId\` 一个方法，参数统一 \`params\` 对象：路径参数自动替换，其余按方法分给 query 或 body；
- 类型在 \`types.ts\`，由 OpenAPI schema 直接映射。

## Python

\`\`\`python
from colanas.client import ColanasClient

c = ColanasClient("http://127.0.0.1:7788", token)
print(c.book_list(limit=20))
\`\`\`

- 只用标准库 \`urllib\`；
- 方法名为 \`operationId\` 的 snake_case 形式；
- 返回值直接是解析后的 dict。

## 说明

- 只覆盖契约里的 HTTP 路由；MCP（stdio）与 sidecar 协议不在 SDK 范围；
- 公开路由（分享下载、HLS 分片）同样生成方法，但 token 为空即可调用。
`;
}

// ---------------------------------------------------------------- 写入 / 校验

const files = new Map([
  [path.join(root, 'sdk', 'typescript', 'types.ts'), buildTypesTs()],
  [path.join(root, 'sdk', 'typescript', 'client.ts'), buildClientTs(collectOps())],
  [path.join(root, 'sdk', 'python', 'colanas', 'client.py'), buildClientPy(collectOps())],
  [path.join(root, 'sdk', 'README.md'), buildReadme()],
]);

let stale = 0;
for (const [file, content] of files) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (checkOnly) {
    if (current !== content) {
      console.error(`[sdk] ${path.relative(root, file)} 已过期，请运行 npm run sdk`);
      stale += 1;
    }
    continue;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf8');
  console.log(`[sdk] wrote ${path.relative(root, file)}`);
}

if (checkOnly) {
  console.log(stale === 0 ? '[sdk] ok' : `[sdk] ${stale} 个文件过期`);
  process.exit(stale === 0 ? 0 : 1);
}
console.log(`[sdk] ${collectOps().length} operations`);
